//! The locales of ICU 74 that `pg_import_system_collations` makes a collation for, with the version and the comment of each collation.
//!
//! PostgreSQL makes a collation for each locale of `uloc_getAvailable`, with the root locale first. The name of the collation is the language tag of the locale with `-x-icu` at its end. The version is the collator version that `ucol_getVersion` gives, and the comment is the display name in English of `uloc_getDisplayName`, or none when that name is not all ASCII. rupg has no ICU library, so this table holds the result of PostgreSQL 19 with ICU 74 for these steps.

/// The collator version of a locale that uses the rules of the root locale, as `get_collation_actual_version` writes it.
pub const ROOT_VERSION: &str = "153.121";

/// The collator version of a locale that has its own collation rules.
pub const TAILORED_VERSION: &str = "153.121.44.8";

/// A locale of ICU that has a collation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct IcuLocale {
    /// The language tag, the value of `colllocale`.
    pub tag: &'static str,
    /// The collator version, the value of `collversion`.
    pub version: &'static str,
    /// The comment of the collation, or `None`.
    pub comment: Option<&'static str>,
}

/// The locales of ICU 74 in the order of `pg_import_system_collations`.
pub fn locales() -> impl Iterator<Item = IcuLocale> {
    LOCALES.iter().map(|&(tag, tailored, comment)| IcuLocale {
        tag,
        version: if tailored { TAILORED_VERSION } else { ROOT_VERSION },
        comment,
    })
}

