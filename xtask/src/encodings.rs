//! The tables of the single-byte encodings, from the conversion maps of PostgreSQL.
//!
//! `cargo xtask encodings [--check]` writes `crates/rupg-func/src/generated/single_byte.rs` and `crates/rupg-func/src/generated/double_byte.rs`. Each input is a map `<encoding>_to_utf8.map` of `src/backend/utils/mb/Unicode`, a `pg_mb_radix_tree` that gives the UTF-8 bytes of each byte of the encoding. The output gives the code point of each byte from 0x80 to 0xFF, or 0 for a byte with no character. The maps from UTF-8 are the inverse of these maps, so they are not vendored. The map of each double-byte encoding gives the code point of each pair of bytes in the ranges of the first and the second byte.

use std::fmt::Write as _;
use std::path::Path;

use crate::read;

const INPUT: &str = "vendor/postgres-19/src/backend/utils/mb/Unicode";
const OUTPUT: &str = "crates/rupg-func/src/generated/single_byte.rs";
const DOUBLE_OUTPUT: &str = "crates/rupg-func/src/generated/double_byte.rs";

/// The name of the map of each double-byte encoding, and the name of the encoding in `pg_enc2name_tbl`.
const DOUBLE_MAPS: [(&str, &str); 1] = [("euc_kr", "EUC_KR")];

/// The name of the map of each encoding, and the name of the encoding in `pg_enc2name_tbl`.
const MAPS: [(&str, &str); 26] = [
    ("iso8859_2", "LATIN2"),
    ("iso8859_3", "LATIN3"),
    ("iso8859_4", "LATIN4"),
    ("iso8859_9", "LATIN5"),
    ("iso8859_10", "LATIN6"),
    ("iso8859_13", "LATIN7"),
    ("iso8859_14", "LATIN8"),
    ("iso8859_15", "LATIN9"),
    ("iso8859_16", "LATIN10"),
    ("win1256", "WIN1256"),
    ("win1258", "WIN1258"),
    ("win866", "WIN866"),
    ("win874", "WIN874"),
    ("koi8r", "KOI8R"),
    ("win1251", "WIN1251"),
    ("win1252", "WIN1252"),
    ("iso8859_5", "ISO_8859_5"),
    ("iso8859_6", "ISO_8859_6"),
    ("iso8859_7", "ISO_8859_7"),
    ("iso8859_8", "ISO_8859_8"),
    ("win1250", "WIN1250"),
    ("win1253", "WIN1253"),
    ("win1254", "WIN1254"),
    ("win1255", "WIN1255"),
    ("win1257", "WIN1257"),
    ("koi8u", "KOI8U"),
];

pub(crate) fn run(root: &Path, args: &[String]) -> Result<(), String> {
    let check = args.iter().any(|a| a == "--check");
    if let Some(other) = args.iter().find(|a| *a != "--check") {
        return Err(format!("encodings: unknown argument {other:?}"));
    }
    let mut text = String::from(
        "//! The single-byte encodings. Generated by `cargo xtask encodings` from the maps in `vendor/postgres-19/src/backend/utils/mb/Unicode`. Do not edit.\n\n/// The code point of each byte from 0x80 to 0xFF of each single-byte encoding, by the name of the encoding. 0 is a byte with no character.\n",
    );
    let _ = writeln!(text, "pub(crate) const TABLES: [(&str, [u16; 128]); {}] = [", MAPS.len());
    for (map, name) in MAPS {
        let file = format!("{map}_to_utf8.map");
        let table =
            high_half(&read(&root.join(INPUT).join(&file))?).map_err(|e| format!("{file}: {e}"))?;
        let _ = writeln!(text, "    (\"{name}\", [");
        for row in table.chunks(8) {
            let row: Vec<String> = row.iter().map(|c| format!("0x{c:04x}")).collect();
            let _ = writeln!(text, "        {},", row.join(", "));
        }
        let _ = writeln!(text, "    ]),");
    }
    text.push_str("];\n");
    write(root, OUTPUT, &text, check)?;

    let mut text = String::from(
        "//! The double-byte encodings. Generated by `cargo xtask encodings` from the maps in `vendor/postgres-19/src/backend/utils/mb/Unicode`. Do not edit.\n\n/// The map of a double-byte encoding.\npub(crate) struct DoubleByte {\n    /// The name of the encoding.\n    pub(crate) name: &'static str,\n    /// The lowest and the highest first byte.\n    pub(crate) first: (u8, u8),\n    /// The lowest and the highest second byte.\n    pub(crate) second: (u8, u8),\n    /// The code point of each pair of bytes. The pair of the first byte `a` and the second byte `b` is at `(a - first.0) * (second.1 - second.0 + 1) + b - second.0`. 0 is a pair with no character.\n    pub(crate) table: &'static [u16],\n}\n\n/// The map of each double-byte encoding.\n",
    );
    let _ = writeln!(text, "pub(crate) const TABLES: [DoubleByte; {}] = [", DOUBLE_MAPS.len());
    for (map, name) in DOUBLE_MAPS {
        let file = format!("{map}_to_utf8.map");
        let (first, second, table) =
            two_bytes(&read(&root.join(INPUT).join(&file))?).map_err(|e| format!("{file}: {e}"))?;
        let _ = writeln!(
            text,
            "    DoubleByte {{ name: \"{name}\", first: (0x{:02x}, 0x{:02x}), second: (0x{:02x}, 0x{:02x}), table: &[",
            first.0, first.1, second.0, second.1
        );
        for row in table.chunks(8) {
            let row: Vec<String> = row.iter().map(|c| format!("0x{c:04x}")).collect();
            let _ = writeln!(text, "        {},", row.join(", "));
        }
        let _ = writeln!(text, "    ] }},");
    }
    text.push_str("];\n");
    write(root, DOUBLE_OUTPUT, &text, check)
}

/// Writes the text to the output, or with `--check` fails when the output is not the text.
fn write(root: &Path, output: &str, text: &str, check: bool) -> Result<(), String> {
    let file = root.join(output);
    if std::fs::read_to_string(&file).unwrap_or_default() == text {
        println!("encodings: {output} matches {INPUT}");
        return Ok(());
    }
    if check {
        return Err(format!("encodings: {output} is not up to date, run `cargo xtask encodings`"));
    }
    std::fs::write(&file, text).map_err(|e| format!("could not write {output}: {e}"))?;
    println!("encodings: wrote {output}");
    Ok(())
}

/// The text without its C comments.
fn without_comments(text: &str) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(start) = rest.find("/*") {
        out.push_str(&rest[..start]);
        rest = rest[start..].find("*/").map_or("", |end| &rest[start + end + 2..]);
    }
    out.push_str(rest);
    out
}

/// The numbers of a list of C hex literals, separated by commas.
fn numbers(list: &str) -> Result<Vec<u32>, String> {
    list.split(',')
        .map(str::trim)
        .filter(|n| !n.is_empty())
        .map(|n| {
            let hex = n.strip_prefix("0x").ok_or_else(|| format!("{n:?} is not a hex number"))?;
            u32::from_str_radix(hex, 16).map_err(|e| format!("{n:?}: {e}"))
        })
        .collect()
}

/// The code point of a character in UTF-8, given as the integer of its bytes, as the maps of PostgreSQL give it.
fn code_point(utf8: u32) -> Result<u16, String> {
    let bytes: Vec<u8> = utf8.to_be_bytes().into_iter().skip_while(|b| *b == 0).collect();
    let c = std::str::from_utf8(&bytes)
        .ok()
        .and_then(|s| s.chars().next())
        .ok_or_else(|| format!("0x{utf8:x} is not a character in UTF-8"))?;
    u16::try_from(u32::from(c)).map_err(|_| format!("U+{:04X} is not in the BMP", u32::from(c)))
}

/// The text between the first `{` after `at` and the `};` that ends it.
fn block_at(text: &str, at: usize) -> Result<&str, String> {
    let open = at + text[at..].find('{').ok_or("no {")? + 1;
    let close = open + text[open..].find("};").ok_or("no };")?;
    Ok(&text[open..close])
}

/// The fields of the `pg_mb_radix_tree` of a map, and the values of its table of 32-bit values.
fn tree(text: &str) -> Result<(Vec<String>, Vec<u32>), String> {
    let text = without_comments(text);
    let tree = block_at(&text, text.find("pg_mb_radix_tree").ok_or("no tree")?)?;
    let fields = tree.split(',').map(|f| f.trim().to_owned()).collect();
    // The table is declared first and defined after the tree, so its text is the block after `] =`.
    let at = text.find("_tree_table[").ok_or("no table")?;
    let values = numbers(block_at(&text, at + text[at..].find("] =").ok_or("no table")?)?)?;
    Ok((fields, values))
}

/// The range of the first byte, the range of the second byte and the code point of each pair of bytes of a double-byte encoding.
type DoubleByte = ((u8, u8), (u8, u8), Vec<u16>);

/// The ranges of the first and the second byte, and the code point of each pair of bytes, from the text of a map of an encoding with inputs of only two bytes, as `pg_mb_radix_conv` looks them up.
fn two_bytes(text: &str) -> Result<DoubleByte, String> {
    let (fields, values) = tree(text)?;
    let one = |n: usize| -> Result<u32, String> {
        let v = numbers(fields.get(n).map_or("", String::as_str))?;
        v.first().copied().ok_or_else(|| format!("no field {n} in the tree"))
    };
    if one(3)? != 0 || one(4)? != 0 || (10..fields.len()).any(|n| one(n).is_ok_and(|v| v != 0)) {
        return Err("the map has inputs of other lengths than two bytes".into());
    }
    let byte = |n: usize| one(n).and_then(|v| u8::try_from(v).map_err(|e| e.to_string()));
    let (root, first, second) = (one(5)? as usize, (byte(6)?, byte(7)?), (byte(8)?, byte(9)?));
    let value = |at: usize| values.get(at).copied().ok_or_else(|| format!("no value at {at}"));
    let mut out = Vec::new();
    for a in first.0..=first.1 {
        let row = value(root + usize::from(a - first.0))? as usize;
        for b in second.0..=second.1 {
            let v = value(row + usize::from(b - second.0))?;
            out.push(if v == 0 { 0 } else { code_point(v)? });
        }
    }
    Ok((first, second, out))
}

/// The code points of the bytes 0x80 to 0xFF from the text of a map.
fn high_half(text: &str) -> Result<[u16; 128], String> {
    let text = without_comments(text);
    // The fields of the tree: the tables, then the offset, the lower and the upper byte of the 1-byte inputs, then the fields of the longer inputs.
    let tree = block_at(&text, text.find("pg_mb_radix_tree").ok_or("no tree")?)?;
    let fields: Vec<&str> = tree.split(',').map(str::trim).collect();
    let field = |n: usize| numbers(fields.get(n).copied().unwrap_or_default());
    let one = |n: usize| -> Result<usize, String> {
        let v = field(n)?;
        v.first().map(|v| *v as usize).ok_or_else(|| format!("no field {n} in the tree"))
    };
    let (offset, lower, upper) = (one(2)?, one(3)?, one(4)?);
    if (5..fields.len()).any(|n| field(n).is_ok_and(|v| v.iter().any(|v| *v != 0))) {
        return Err("the map has inputs of more than one byte".into());
    }
    // The table is declared first and defined after the tree, so its text is the block after `] =`.
    let at = text.find("_tree_table[").ok_or("no table")?;
    let values = numbers(block_at(&text, at + text[at..].find("] =").ok_or("no table")?)?)?;
    let mut out = [0u16; 128];
    for b in 0x80..=0xffusize {
        if b < lower || b > upper {
            continue;
        }
        let v = *values.get(offset + b - lower).ok_or_else(|| format!("no value for 0x{b:02x}"))?;
        if v != 0 {
            out[b - 0x80] = code_point(v)?;
        }
    }
    Ok(out)
}
